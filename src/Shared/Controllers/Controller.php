<?php

namespace App\Shared\Controllers;

abstract class Controller
{
    protected function successResponse($message = 'Success', $data = [], $status = 200)
    {
        return response()->json([
            'success' => true,
            'message' => $message,
            'data' => $data,
        ], $status);
    }

    protected function errorResponse($message = 'An error occurred', $errors = [], $status = 400)
    {
        return response()->json([
            'success' => false,
            'message' => $message,
            'errors' => $errors,
        ], $status);
    }
}
